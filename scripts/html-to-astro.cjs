const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const generated = path.join(root, '.generated');
const pages = path.join(root, 'src', 'pages');
const publicDir = path.join(root, 'public');
const site = JSON.parse(fs.readFileSync(path.join(root, 'content', 'site.json'), 'utf8'));
const base = site.domain.replace(/\/$/, '');

function copyDir(src, dest) {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    entry.isDirectory() ? copyDir(from, to) : fs.copyFileSync(from, to);
  }
}

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    entry.isDirectory() ? out.push(...walk(full)) : out.push(full);
  }
  return out;
}

function normalized(relative) {
  return relative.split(path.sep).join('/');
}

function cleanPath(relativeHtml) {
  const rel = normalized(relativeHtml);
  if (rel === 'index.html') return '/';
  if (rel.endsWith('/index.html')) return `/${rel.slice(0, -'index.html'.length)}`;
  return `/${rel.replace(/\.html$/, '')}/`;
}

function cleanEndpointPath(relativeHtml) {
  const dir = path.dirname(relativeHtml);
  const filename = path.basename(relativeHtml);
  if (filename === 'index.html') {
    return path.join(pages, dir === '.' ? '' : dir, 'index.html.ts');
  }
  const slug = filename.replace(/\.html$/, '');
  return path.join(pages, dir === '.' ? '' : dir, slug, 'index.html.ts');
}

function legacyEndpointPath(relativeHtml) {
  return path.join(pages, `${relativeHtml}.ts`);
}

function endpointSource(html) {
  return `// Generated Astro endpoint. Returns the approved HTML without Vite parsing inline tracking scripts.\n` +
    `export const prerender = true;\n` +
    `const html = ${JSON.stringify(html)};\n` +
    `export function GET() {\n` +
    `  return new Response(html, { headers: { 'Content-Type': 'text/html; charset=utf-8' } });\n` +
    `}\n`;
}

function injectIndexCleanup(html) {
  const script = `<script>(function(){if(location.pathname.endsWith('/index.html')){history.replaceState(null,'',location.pathname.replace(/index\\.html$/,'')+location.search+location.hash);}})();</script>`;
  return html.includes('</head>') ? html.replace('</head>', `${script}\n</head>`) : `${script}\n${html}`;
}

function redirectHtml(targetPath) {
  const canonical = `${base}${targetPath}`;
  const targetJson = JSON.stringify(targetPath);
  return `<!doctype html>\n<html lang="ar" dir="rtl">\n<head>\n<meta charset="utf-8">\n<meta name="robots" content="noindex,follow">\n<link rel="canonical" href="${canonical}">\n<meta http-equiv="refresh" content="0;url=${targetPath}">\n<title>جارٍ التحويل…</title>\n<script>location.replace(${targetJson}+location.search+location.hash);</script>\n</head>\n<body><p>جارٍ تحويلك إلى <a href="${targetPath}">${canonical}</a></p></body>\n</html>\n`;
}

function middlewareSource(routes) {
  const routeHtml = Object.fromEntries(routes);
  return `// Generated by scripts/html-to-astro.cjs. Serves clean URLs directly in Astro dev.\n` +
    `import { defineMiddleware } from "astro:middleware";\n\n` +
    `const routeHtml: Record<string, string> = ${JSON.stringify(routeHtml)};\n\n` +
    `export const onRequest = defineMiddleware((context, next) => {\n` +
    `  const rawPath = context.url.pathname;\n` +
    `  const cleanPath = rawPath === "/" ? "/" : \`\${rawPath.replace(/\\/+$/, "")}\/\`;\n` +
    `  const html = routeHtml[cleanPath];\n` +
    `  if (!html) return next();\n` +
    `  return new Response(html, { headers: { "Content-Type": "text/html; charset=utf-8" } });\n` +
    `});\n`;
}

if (!fs.existsSync(generated)) throw new Error('Missing .generated output. Run generate-static.cjs first.');

fs.rmSync(pages, { recursive: true, force: true });
fs.rmSync(publicDir, { recursive: true, force: true });
fs.mkdirSync(pages, { recursive: true });
fs.mkdirSync(publicDir, { recursive: true });

let cleanCount = 0;
let redirectCount = 0;
const cleanRoutes = [];
for (const file of walk(generated)) {
  const relative = path.relative(generated, file);
  const rel = normalized(relative);
  if (!file.endsWith('.html') || rel.startsWith('admin/')) continue;

  const target = cleanPath(relative);
  const cleanOutput = cleanEndpointPath(relative);
  let html = fs.readFileSync(file, 'utf8');
  if (path.basename(relative) === 'index.html') html = injectIndexCleanup(html);
  fs.mkdirSync(path.dirname(cleanOutput), { recursive: true });
  fs.writeFileSync(cleanOutput, endpointSource(html));
  cleanRoutes.push([target, html]);
  cleanCount++;

  if (path.basename(relative) !== 'index.html') {
    const legacyOutput = legacyEndpointPath(relative);
    fs.mkdirSync(path.dirname(legacyOutput), { recursive: true });
    fs.writeFileSync(legacyOutput, endpointSource(redirectHtml(target)));
    redirectCount++;
  }
}

fs.writeFileSync(path.join(root, 'src', 'middleware.ts'), middlewareSource(cleanRoutes));

copyDir(path.join(root, 'assets'), path.join(publicDir, 'assets'));
copyDir(path.join(root, 'admin'), path.join(publicDir, 'admin'));
for (const name of ['robots.txt', 'sitemap.xml', '_redirects']) {
  const source = path.join(generated, name);
  if (fs.existsSync(source)) fs.copyFileSync(source, path.join(publicDir, name));
}
fs.writeFileSync(path.join(publicDir, '.nojekyll'), '');

console.log(`Prepared ${cleanCount} clean Astro routes and ${redirectCount} legacy redirects.`);
